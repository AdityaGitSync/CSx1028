#include<iostream>
int main()
{
    int a = 10; // Declare an integer variable 'a' and initialize it with the value 10
    float b = 5.5; // Declare a float variable 'b' and initialize it with the value 5.5
    char c = 'A'; // Declare a char variable 'c' and initialize it with the character 'A'
    bool d = true; // Declare a boolean variable 'd' and initialize it with the value true
    std::string e = "Hello, World!"; // Declare a string variable 'e' and initialize it with the value "Hello, World!"
    //string:-(object that represents a sequence of text characters)

    std::cout << "Integer: " << a << std::endl; // Output the value of 'a'
    std::cout << "Float: " << b << std::endl; // Output the value of 'b'
    std::cout << "Character: " << c << std::endl; // Output the value of 'c'
    std::cout << "Boolean: " << d << std::endl; // Output the value of 'd'
    std::cout << "String: " << e << std::endl; // Output the value of 'e'

    return 0;
}